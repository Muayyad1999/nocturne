//! | 192.0.2.80:443 → 10.0.0.5:51000 tcp | 22 | 24,880 |
//! | 10.0.0.5:40000 → 10.0.0.53:53 udp | 1 | 58 |
//! | 10.0.0.53:53 → 10.0.0.5:40000 udp | 1 | 118 |
//! | 10.0.0.7:16384 → 10.0.0.9:16384 udp, ToS 0xb8 (EF) | 50 | 9,400 |
//! | 10.0.0.5 → 10.0.0.1 icmp echo request | 3 | 180 |
//! | 2001:db8::5:52000 → 2001:db8::22:22 tcp | 6 | 860 |
//!
//! nfdump read softflowd's v9 export the same way (`nfcapd` collecting, `nfdump -o csv`):
//! 7 flows, 105 packets, 36,376 bytes, ToS 184 on the voice flow.
//!
