//! Export datagrams real exporters sent, written down as hex.
//!
//! Where they come from: softflowd 1.1.0 and nfdump 1.7.3 (the Ubuntu 24.04 packages
//! `1.1.0-1build2` and `1.7.3-1build2`), run on 2026-11-23 on the machine this was developed
//! on. softflowd was given a capture file (`softflowd -r traffic.pcap -n 127.0.0.1:<port>
//! -v <version> -6 -d`) and what it sent to the port was written down byte for byte. The
//! export datagrams are softflowd's and nfreplay's own; the *traffic* in the capture file is
//! not from a network — it is the five conversations of [`super::traffic`], written by hand,
//! which is what makes it possible to say what the right answer is:
//!
